-- Source data for the Shop and Shine catalog.

local function entry(data)
	data.Image = data.Image or ""
	data.Description = data.Description or ""
	data.Category = data.Category or data.Type
	data.Rarity = data.Rarity or "Common"
	data.Theme = data.Theme or "Neutral"
	data.ThemeTags = data.ThemeTags or { string.lower(data.Theme) }
	data.Department = data.Department
	data.StoreSubsection = data.StoreSubsection or "Decor"
	data.PlacementSurface = data.PlacementSurface or "Floor"
	data.SpawnChance = data.SpawnChance or 0.55
	if data.ShowroomEligible == nil then
		data.ShowroomEligible = data.Department ~= nil
	end
	return data
end

